test("disclosure package: no-view-key banner, encrypted download, log without content", async ({ page }) => {
  await shield(page, "30");
  await page.getByRole("button", { name: "Shield 30.00 USDG" }).click();
  await acceptTos(page);
  await expect(page.getByRole("heading", { name: /recorded/ })).toBeVisible({ timeout: 10_000 });
  await page.goto("/app/keys/");
  await expect(page.getByText("This protocol build does not offer a view-only key.")).toBeVisible();
  const prep = page.getByRole("region", { name: "Prepare a package" });
  await prep.getByLabel("Password", { exact: true }).fill("short");
  await page.getByRole("button", { name: "Prepare package" }).click();
  await expect(page.getByText("Use at least 12 characters.")).toBeVisible();
  await prep.getByLabel("Password", { exact: true }).fill("a long enough passphrase");
  const [dl] = await Promise.all([page.waitForEvent("download"), page.getByRole("button", { name: "Prepare package" }).click()]);
  expect(dl.suggestedFilename()).toMatch(/^disclosure-package-mock-\d{4}-\d{2}-\d{2}\.csv\.encrypted\.json$/);
  await expect(page.getByText(/CSV · 1 record · encrypted/)).toBeVisible();
  const stored = await page.evaluate(() => JSON.stringify(Object.fromEntries(Object.entries(localStorage))));
  expect(stored).not.toContain("a long enough passphrase");
  expect(stored).not.toMatch(/view.?key/i);
});

