test("keyboard: skip link, dialog closes on Escape and returns focus", async ({ page }) => {
  await page.goto("/app/settings/");
  await page.keyboard.press("Tab");
  await expect(page.getByRole("link", { name: "Skip to main content" })).toBeFocused();
  const trigger = page.getByRole("button", { name: "Clear mock data" });
  await trigger.focus();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("dialog", { name: "Clear mock data?" })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await expect(trigger).toBeFocused();
});

test("no horizontal scroll at 360px and a mock banner on every app screen", async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 });
  for (const r of ["/", "/app/shield/", "/app/transfer/", "/app/unshield/", "/app/activity/", "/app/keys/", "/app/settings/", "/legal/terms/", "/legal/privacy/", "/legal/disclosures/", "/styleguide/", "/missing-page/"]) {
    await page.goto(r);
    const sw = await page.evaluate(() => document.documentElement.scrollWidth);
    expect(sw, r).toBeLessThanOrEqual(360);
    if (r.startsWith("/app/")) await expect(page.getByText("Mock mode: no real funds are moved.").first(), r).toBeVisible();
  }
});

